"""Rebuild the responses with NA masked rather than zeroed, and recompute Figure 1.

The ordering survives the convention (Spearman between missingness and the Figure 1 value is
-0.100), but each species carries a different fraction of structurally-zero genes -- 32.3% of
the axis for rabbit, 14.2% for macaque, 0% for human -- and those genes contribute a constant
zero to every contrast, which dilutes a correlation rather than biasing its rank. This asks
what each species' value becomes when those cells are excluded instead of zeroed.
"""
import csv, json, sys
import numpy as np

D = 'artifacts/gse249010_v1/processed/'
# Generated by run_na_audit.py from the public TPM table.
SP = 'artifacts/gse249010_v1/na_cache/'
M = np.load(SP + 'na_mask.npy')            # True where the raw token was NA
V = np.load(SP + 'raw_vals.npy')           # NA already coerced to 0, as the pipeline does

meta = list(csv.DictReader(open(D + 'sample_metadata.tsv'), delimiter='\t'))
import gzip
with gzip.open('artifacts/gse249010_v1/data/GSE249010_processed_data_TPM.txt.gz', 'rt') as fh:
    cols = fh.readline().rstrip('\n').split('\t')[1:]
by_id = {m['sample_id']: m for m in meta}

X = np.log2(np.maximum(V, 0.0) + 1.0)      # same transform
Xm = X.copy(); Xm[M] = np.nan              # masked variant

SEL_DOSE = {'10', '100', '1000'}; SEL_TIME = {'2', '6', '24'}
keep = [j for j, c in enumerate(cols)
        if by_id[c]['time'] in SEL_TIME and (by_id[c]['dose'] in SEL_DOSE or by_id[c]['treatment'] == 'NC')]
rows = [by_id[cols[j]] for j in keep]

def build(mat):
    """response = treated - matched same-subject same-time control, as the pipeline does."""
    groups = {}
    for i, r in enumerate(rows):
        groups.setdefault((r['subject'], r['time'], r['organism']), []).append(i)
    out, meta_out = [], []
    for k, idxs in sorted(groups.items()):
        ctrl = [i for i in idxs if rows[i]['dose'] == '0']
        if len(ctrl) != 1: continue
        c = mat[:, keep[ctrl[0]]]
        for i in idxs:
            if rows[i]['dose'] == '0': continue
            out.append(mat[:, keep[i]] - c)
            meta_out.append({'species': rows[i]['organism'], 'subject': rows[i]['subject'],
                             'task': f"LPS|{rows[i]['dose']}ngml|{rows[i]['time']}h"})
    return np.vstack(out), meta_out

def pear(a, b):
    m = np.isfinite(a) & np.isfinite(b)
    if m.sum() < 100: return np.nan
    a, b = a[m], b[m]
    a = a - a.mean(); b = b - b.mean()
    d = np.sqrt((a*a).sum() * (b*b).sum())
    return float((a*b).sum()/d) if d > 0 else np.nan

SH = {'Pan troglodytes':'chimp','Macaca':'macaque','Papio anubis':'baboon','Bos taurus':'cow',
      'Oryctolagus cuniculus':'rabbit','Ovis aries':'sheep','Sus scrofa':'pig',
      'Mus musculus':'mouse','Rattus norvegicus':'rat','Homo sapiens':'human'}
H = 'Homo sapiens'
res = {}
for lab, mat in (('zeroed', X), ('masked', Xm)):
    R, md = build(mat)
    sp = sorted({m['species'] for m in md}); tk = sorted({m['task'] for m in md})
    tk = [t for t in tk if all(any(m['species']==s and m['task']==t for m in md) for s in sp)]
    mean = {s: {t: np.nanmean(R[[i for i,m in enumerate(md) if m['species']==s and m['task']==t]], axis=0)
                for t in tk} for s in sp}
    res[lab] = {s: float(np.nanmean([pear(mean[s][t], mean[H][t]) for t in tk]))
                for s in sp if s != H}
    print(f'{lab}: {R.shape[0]} response rows, {len(tk)} tasks'); sys.stdout.flush()

def spear(a, b):
    import numpy as _n
    ra=_n.argsort(_n.argsort(_n.asarray(a,float))).astype(float); rb=_n.argsort(_n.argsort(_n.asarray(b,float))).astype(float)
    ra=ra-ra.mean(); rb=rb-rb.mean()
    return float((ra*rb).sum()/_n.sqrt((ra*ra).sum()*(rb*rb).sum()))
def _unused(a, b):
    r = lambda v: np.argsort(np.argsort(np.asarray(v, float))).astype(float)
    return pear(r(a), r(b))

order = sorted(res['zeroed'], key=lambda s: -res['zeroed'][s])
print()
print('%-10s %10s %10s %9s'%('species','NA→0','NA masked','变化'))
for s in order:
    print('%-10s %10.4f %10.4f %+9.4f'%(SH[s], res['zeroed'][s], res['masked'][s],
                                        res['masked'][s]-res['zeroed'][s]))
print()
print('Spearman(两种约定下的排序) = %+.3f'
      % spear([res['zeroed'][s] for s in order], [res['masked'][s] for s in order]))
prim = ('Pan troglodytes','Macaca','Papio anubis')
for lab in ('zeroed','masked'):
    p = np.mean([res[lab][s] for s in order if s in prim])
    n = np.mean([res[lab][s] for s in order if s not in prim])
    print('  %-7s 灵长类 %.4f  非灵长类 %.4f  倍数 %.2f'%(lab, p, n, p/n))
json.dump(res, open('artifacts/gse249010_v1/na_masked_fig1.json','w'), indent=1)
print('\nwrote artifacts/gse249010_v1/na_masked_fig1.json')
